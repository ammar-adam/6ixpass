/*
 * The places in the app demo. Every one is made up: the names, people,
 * menus and prices are invented to feel like real Toronto places without
 * being any of them. Addresses are a street and a cross street only, never a
 * number, so they can't point at a real business.
 *
 * Rules: no real business names, no alcohol (offers, menus or photos), no em
 * dashes. Photos: docs/IMAGE-CREDITS.md. Checked by scripts/places-check.mjs.
 *
 * days and hours: Monday first. An offer only runs on days the place is open.
 * saving: menu price of the free item, for "You saved about $X".
 */
import type { Partner } from "./data";

type Open = [open: string, close: string] | null;
export type MenuItem = { name: string; price: number };
export type PlaceDetails = {
  address: string;
  transit: string;
  price: 1 | 2 | 3 | 4;
  /** Seven entries, Monday first, 24-hour "HH:MM"; null when closed. */
  hours: Open[];
  menuTitle: string;
  menu: MenuItem[];
  note: string;
  noteBy: string;
  /** More photos after the main one (same naming as `image`). */
  gallery: string[];
};
export type DemoPlace = Partner & { details: PlaceDetails };

const every = (o: string, c: string): Open[] => Array.from({ length: 7 }, () => [o, c]);
/** Open on the days marked 1, Monday first. */
const on = (mask: string, o: string, c: string): Open[] => [...mask].map((d) => (d === "1" ? [o, c] : null));
const D = (mask: string) => [...mask].map((d) => d === "1");

