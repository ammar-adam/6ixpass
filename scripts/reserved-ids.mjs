// Prints the SQL that fills t6p_private.reserved_place_ids (docs/app/SUPABASE-ACCOUNTS.sql,
// section 0): every place id the app ships with, so create_my_business never gives a new
// business an id the app already uses for a built-in place.
//   node scripts/reserved-ids.mjs            print the insert
//   node scripts/reserved-ids.mjs --check    exit 1 if the SQL file is missing any id
// Run it whenever places change (src/demo/places.ts or data/real-places.csv), paste the
// output over the insert in section 0, and run that insert in the SQL Editor.
import fs from "node:fs";
import path from "node:path";

const ROOT = path.join(path.dirname(new URL(import.meta.url).pathname), "..");
const read = (f) => fs.readFileSync(path.join(ROOT, f), "utf8");

// The app's own routes and the meeting demo's place (src/mock/owner.ts OWNER_ID).
const ROUTES = ["your-place", "view", "new"];

// The made-up places (src/demo/places.ts): each place's own `id:` line.
const fictional = [...read("src/demo/places.ts").matchAll(/^ {4}id: "([a-z0-9-]+)",$/gm)].map((m) => m[1]);

// The real places of the private build: the same ids scripts/real-places.mjs makes
// (first 50 rows of data/real-places.csv, slug of the name, "-2" on repeats).
function parseCsv(text) {
  const rows = [];
  let row = [];
  let cell = "";
  let q = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (q) {
      if (ch === '"' && text[i + 1] === '"') (cell += '"'), i++;
      else if (ch === '"') q = false;
      else cell += ch;
    } else if (ch === '"') q = true;
    else if (ch === ",") row.push(cell), (cell = "");
    else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(cell), (cell = "");
      if (row.some((c) => c !== "")) rows.push(row);
      row = [];
    } else cell += ch;
  }
  if (cell || row.length) row.push(cell), rows.push(row);
  const [head, ...body] = rows;
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h.trim(), (r[i] ?? "").trim()])));
}
const slug = (s) => s.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const real = [];
const seen = new Set();
for (const r of parseCsv(read("data/real-places.csv")).slice(0, 50)) {
  let id = slug(r.name);
  while (seen.has(id)) id += "-2";
  seen.add(id);
  real.push(id);
}

const ids = [...new Set([...ROUTES, ...fictional, ...real])];
if (fictional.length === 0 || real.length === 0) throw new Error("No place ids found: has the layout of places.ts or real-places.csv changed?");

if (process.argv.includes("--check")) {
  const sql = read("docs/app/SUPABASE-ACCOUNTS.sql");
  const missing = ids.filter((id) => !sql.includes(`('${id}')`));
  console.log(missing.length ? `Missing from the SQL: ${missing.join(", ")}` : `All ${ids.length} reserved ids are in the SQL.`);
  process.exit(missing.length ? 1 : 0);
}

const lines = ids.map((id) => `  ('${id}')`);
console.log(`-- Generated by scripts/reserved-ids.mjs: ${ROUTES.length} app routes, ${fictional.length} made-up places, ${real.length} real places.`);
console.log(`insert into t6p_private.reserved_place_ids (id) values\n${lines.join(",\n")}\non conflict (id) do nothing;`);
